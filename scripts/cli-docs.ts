import { HELP } from "../src/help.ts";

/** The contents of docs/cli.md: `bunker --help`, verbatim, in a fence. */
export const cliDoc = () =>
  `# CLI reference\n\n<!-- generated by \`bun run docs:cli\` from \`bunker --help\`; do not edit -->\n\n\`\`\`text\n${HELP.trimEnd()}\n\`\`\`\n`;

if (import.meta.main) {
  await Bun.write(import.meta.dir + "/../docs/cli.md", cliDoc());
  console.log("wrote docs/cli.md");
}
