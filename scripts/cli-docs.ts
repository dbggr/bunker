import { CONFIG_KEYS, formatValue } from "../src/core/config.ts";
import { AUTH_ROWS, COMMON_FLAGS, CONFIG_INTRO, EXAMPLES, EXTRA_KEYS, LABELS, MODEL_ROWS, SECTIONS, type Row } from "../src/cli/commands/doc-data.ts";

// `<n>` outside a code span would be an HTML tag to VitePress; inside one it is literal.
const cell = (s: string) =>
  s
    .split(/(`[^`]*`)/)
    .map((p, i) => (i % 2 ? p : p.replace(/</g, "&lt;")))
    .join("")
    .replace(/\|/g, "\\|")
    .replace(/\n/g, " ");
const table = (head: string[], rows: (string | undefined)[][]) =>
  [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.map((c) => cell(c ?? "")).join(" | ")} |`)].join("\n");
const flagTable = (rows: Row[]) => table(["Flag", "What it does", "Default"], rows.map(([f, w, d]) => [f, w, d ?? ""]));
const fence = (s: string) => `\`\`\`sh\n${s}\n\`\`\``;

/** The contents of docs/cli.md, built from doc-data.ts and the config key table. */
export const cliDoc = () => {
  const out: string[] = ["# CLI reference", "<!-- generated by `bun run docs:cli` from src/cli/commands/doc-data.ts and the config keys; do not edit -->"];
  for (const s of SECTIONS) {
    out.push(`## ${s.title}`);
    for (const c of s.commands) out.push(`### bunker ${c.cmd.replace(/</g, "&lt;").replace(/>/g, "&gt;")}`, c.summary, flagTable(c.rows), fence(c.example));
  }
  out.push("## Common flags", flagTable(COMMON_FLAGS));
  out.push("### Models", table(["Rule", "What it does", "Default"], MODEL_ROWS));
  out.push("### Auth", table(["Variable", "What it does"], AUTH_ROWS));
  out.push("## Config keys", table(["Rule", "What it does"], CONFIG_INTRO));
  out.push(
    table(
      ["Key", "What it does", "Default", "File"],
      [
        ...CONFIG_KEYS.map((k) => [k.key, k.doc, k.default === undefined || (Array.isArray(k.default) && !k.default.length) ? "" : formatValue(k.default), ".bunker/config.toml"]),
        ...EXTRA_KEYS.map((k) => [k.key, k.what, k.dflt, k.file]),
      ],
    ),
  );
  out.push("## Labels", table(["Label", "What sets or clears it"], LABELS));
  out.push("## Examples", fence(EXAMPLES.join("\n")));
  return out.join("\n\n") + "\n";
};

if (import.meta.main) {
  await Bun.write(import.meta.dir + "/../docs/cli.md", cliDoc());
  console.log("wrote docs/cli.md");
}
